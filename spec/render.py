"""Write the method table in spec/README.md from spec/jaah-extension.json; `--check` fails on drift.

Stdlib only, so it runs from a copy of the SDK with nothing installed.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN = "<!-- methods:begin (generated by spec/render.py from jaah-extension.json; never edit by hand) -->"
END = "<!-- methods:end -->"


def table(spec: dict) -> str:
    rows = ["| ACP method | Daemon verb | Required params | Purpose |", "|---|---|---|---|"]
    for method, entry in spec["methods"].items():
        required = ", ".join(f"`{p}`" for p in entry["params"].get("required", [])) or "—"
        purpose = entry["description"].split(". ")[0].split(": ")[0].rstrip(".").replace("|", "\\|")
        if entry.get("memoryOnly"):
            purpose += " (served only while project memory is on)"
        rows.append(f"| `{method}` | `{entry['verb']}` | {required} | {purpose} |")
    return "\n".join(rows)


def render(readme: str, spec: dict) -> str:
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{table(spec)}\n{END}{tail}"


def main(argv: list[str]) -> int:
    spec = json.loads((HERE / "jaah-extension.json").read_text())
    readme_path = HERE / "README.md"
    current = readme_path.read_text()
    wanted = render(current, spec)
    if "--check" in argv:
        if current != wanted:
            print("spec/README.md method table is stale: run `python3 spec/render.py`", file=sys.stderr)
            return 1
        return 0
    readme_path.write_text(wanted)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
